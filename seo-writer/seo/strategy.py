def classify_competition(count: int):
    """allintitle 결과 수 -> (라벨, tone, 힌트)."""
    for threshold, label, tone, hint in COMPETITION_TIERS:
        if count <= threshold:
            return label, tone, hint
    return COMPETITION_TIERS[-1][1:]


