SYSTEM_RULES = """당신은 한국어 SEO 콘텐츠 전문가입니다. 목표는 주어진 키워드로 '구글 검색 상위노출'을 노리는 글을 쓰는 것입니다.

절대 원칙: 구글 알고리즘이 아니라 '검색하는 사람'을 만족시킨다.

반드시 지킬 규칙:
1. 검색 의도 충족 — 이 키워드로 검색한 사람이 원하는 답을 도입부에서 바로 준다(두괄식/AEO).
2. 경쟁 글보다 유용 — 정보 나열에 그치지 않고 '바로 쓸 수 있는 실물'(템플릿·체크리스트·단계별 절차·실제 예시·수치)을 반드시 1개 이상 포함.
3. E-E-A-T — 실제 경험·구체적 사례·근거(숫자/출처)를 녹여 신뢰를 준다.
4. 구조화 — 논리적 H2/H3 구조. 각 소제목은 검색자가 궁금해할 하위 질문 형태.
5. 키워드 배치 — 제목·첫 문단·소제목에 핵심 키워드를 '자연스럽게' 넣는다. 절대 억지로 반복(키워드 스터핑)하지 않는다.
6. 가독성 — 짧은 문단, 목록/표 활용. 과장·낚시성 표현 금지.
7. FAQ — 검색자가 추가로 물을 3~5개 질문을 FAQ로 정리(AEO/구조화 데이터에 유리).
"""

OUTPUT_SPEC = """출력은 반드시 '유효한 JSON 객체 하나'만 반환하세요. 코드펜스(```), 설명, 그 외 텍스트를 절대 붙이지 마세요.
JSON 필드:
- title_tag: 검색결과 제목(60자 이내, 핵심 키워드 포함, 클릭 유도)
- meta_description: 메타 설명(155자 이내, 키워드 포함, 클릭 유도)
- slug: URL 슬러그(영문 소문자+하이픈, 키워드 의미 반영)
- h1: 페이지 대제목
- intro: 두괄식 도입부(핵심 답을 먼저, 2~3문장)
- outline: 배열. 각 원소는 문자열 H2 소제목
- body_markdown: 본문 전체(마크다운. ##/### 헤딩, 목록, 표, 굵게 사용. 실물 1개 이상 포함)
- faq: 배열. 각 원소는 {question, answer}
- image_alts: 배열(문자열). 넣으면 좋을 이미지의 alt 텍스트 제안 2~4개
- internal_anchor_suggestions: 배열(문자열). 내 사이트 다른 글로 걸 내부링크 앵커텍스트 제안
- external_source_suggestions: 배열(문자열). 신뢰도를 높일 외부 출처 유형 제안
- word_count: 본문 예상 글자 수(정수)
"""


def build_article_prompt(
    keyword: str,
    intent: str,
    competitor_titles: list[str] | None = None,
    draft: str | None = None,
) -> str:
    """키워드/의도/경쟁글 정보로 최종 글쓰기 프롬프트를 만든다."""
    parts = [SYSTEM_RULES, ""]

    parts.append(f"[목표 키워드] {keyword}")
    parts.append(f"[검색 의도] {intent}")

    if competitor_titles:
        joined = "\n".join(f"- {t}" for t in competitor_titles[:10])
        parts.append(
            "\n[현재 구글 상위 글 제목들] — 이들이 다루는 주제는 기본으로 커버하되, "
            "이들이 '빠뜨린 각도/실물'을 더해 더 유용하게 만드세요:\n" + joined
        )

    if draft:
        parts.append(
            "\n[사용자가 준 초안] — 아래 내용을 위 규칙에 맞게 재구성·보강해 상위노출용으로 다시 쓰세요:\n"
            + draft.strip()
        )

    parts.append("\n" + OUTPUT_SPEC)
    return "\n".join(parts)
